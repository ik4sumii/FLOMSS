#!/usr/bin/env python3
"""Build the static objective-results payload used by the FLOMSS demo page."""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path


HERE = Path(__file__).resolve().parent
INPUT = HERE.parent / "scripts" / "results_average.csv"
OUTPUT = HERE / "results_data.js"

MODEL_NAMES = {
    "cfm/a05_b015_sy_05_x_5_<STEM>_48k-remix-xloss": "FLOMSS-S",
    "cfm/a05_b015_sy_05_x_5_<STEM>_48k-remix-xloss-predictive": "FLOMSS-Disc.",
    "cfm/a05_b015_sy_05_x_5_<STEM>_48k-remix-xloss-sgmsvs-old": "FLOMSS-M",
    "htdemucs": "HTDemucs",
    "instglow": "InstGlow",
    "mge_ldm": "MGE-LDM",
    "openunmix": "Open-Unmix",
    "scnet": "SCNet",
    "sam_audio_small": "SAM Audio",
}

MODEL_ORDER = (
    "SCNet",
    "HTDemucs",
    "Open-Unmix",
    "FLOMSS-Disc.",
    "InstGlow",
    "MGE-LDM",
    "SAM Audio",
    "FLOMSS-S",
    "FLOMSS-M",
)

METRICS = (
    "signal_mel",
    "signal_waveform",
    "signal_nsdr",
    "bss_sir",
    "bss_sar",
    "FD-VGGish",
    "FD-PASST",
    "FD-OpenL3",
    "FD-LAION-CLAP",
    "FD-MERT",
    "MMD-VGGish",
    "MMD-PASST",
    "MMD-OpenL3",
    "MMD-LAION-CLAP",
    "MMD-MERT",
    "LPAPS-VGGish",
    "LPAPS-PASST",
    "LPAPS-OpenL3",
    "LPAPS-LAION-CLAP",
    "LPAPS-MERT",
)


def finite_number(value: str):
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def main() -> int:
    with INPUT.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))

    output_rows = []
    for row in rows:
        raw_model = row.get("model", "")
        if not raw_model:
            continue
        model = MODEL_NAMES.get(raw_model)
        if model is None:
            raise KeyError(f"No display name configured for model: {raw_model}")
        raw_source = row.get("stem", "")
        source = "average" if raw_source.startswith("avg(") else raw_source
        if source not in {"average", "vocals", "bass", "drums", "other"}:
            continue
        output_rows.append(
            {
                "model": model,
                "source": source,
                "metrics": {metric: finite_number(row.get(metric, "")) for metric in METRICS},
            }
        )

    expected = len(MODEL_ORDER) * 5
    if len(output_rows) != expected:
        raise RuntimeError(f"Expected {expected} result rows, found {len(output_rows)}")

    order = {model: index for index, model in enumerate(MODEL_ORDER)}
    source_order = {source: index for index, source in enumerate(("average", "vocals", "bass", "drums", "other"))}
    output_rows.sort(key=lambda row: (source_order[row["source"]], order[row["model"]]))
    payload = {
        "modelOrder": MODEL_ORDER,
        "rows": output_rows,
    }
    text = "// Generated by generate_results_data.py.\nwindow.FLOMSS_RESULTS = "
    text += json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    text += ";\n"
    temporary = OUTPUT.with_suffix(".js.tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(OUTPUT)
    print(f"Wrote {OUTPUT} ({len(output_rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
